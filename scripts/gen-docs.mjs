// ---------------------------------------------------------------- SUMMARY
function parseSummary() {
  const sections = [];
  let cur = { title: "Overview", pages: [] };
  sections.push(cur);
  for (const line of read("SUMMARY.md").split("\n")) {
    const h = /^##\s+(.+)$/.exec(line);
    if (h) {
      cur = { title: h[1].trim(), pages: [] };
      sections.push(cur);
      continue;
    }
    const m = /^\*\s+\[([^\]]+)\]\(([^)]+)\)/.exec(line);
    if (m) cur.pages.push({ title: m[1], path: m[2] });
  }
  return sections.filter((s) => s.pages.length > 0);
}
const slugOf = (path) => (path === "README.md" ? "" : path.replace(/\.md$/, ""));
const urlOf = (path) => (slugOf(path) ? `${BASE}/${slugOf(path)}` : BASE);

function firstSentence(text) {
  const lines = text.split("\n");
  let i = lines.findIndex((l) => /^#\s/.test(l));
  for (i = i + 1; i < lines.length; i++) {
    const l = lines[i].trim();
    if (!l || l.startsWith("#") || l.startsWith(">") || l.startsWith("<!--") || l.startsWith("|") || l.startsWith("![") ||  l.startsWith("```") || l.startsWith("- ")) continue;
    const plain = l.replace(/\[([^\]]+)\]\([^)]*\)/g, "$1").replace(/\*\*/g, "");
    let acc = "";
    for (const sentence of plain.split(/(?<=[.!?])\s/)) {
      acc = acc ? `${acc} ${sentence}` : sentence;
      if (acc.length >= 80) break;
    }
    return acc.length > 220 ? `${acc.slice(0, 217).trimEnd()}...` : acc;
  }
  return "";
}

function stripComments(text) {
  return text.replace(/<!--[\s\S]*?-->\n?/g, "");
}

