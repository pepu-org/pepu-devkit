#!/usr/bin/env node
// Generates the docs pages that are derived from code.
//
//   docs/reference/errors.md     PEPU_ERROR_CATALOG + paymaster denial reasons
//   docs/sdk/errors.md           the same catalog as a compact table
//   docs/reference/endpoints.md  src/endpoints.ts (PEPU_HOSTED, PEPU_ENV) + contract registry
//   docs/llms.txt                concise index (llms.txt convention)
//   docs/llms-full.txt           every page in SUMMARY.md, HTML comments stripped
//
// Usage (after `pnpm --filter @pepu-chain/sdk build`):
//   node scripts/gen-docs.mjs            write the files
//   node scripts/gen-docs.mjs --check    exit 1 if any generated file is stale
//
// The output is deterministic: no dates, no absolute paths.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const docs = join(root, "docs");
const BASE = "https://docs.pepeunchained.com";
const check = process.argv.includes("--check");

const sdkDist = join(root, "packages", "sdk", "dist");
if (!existsSync(join(sdkDist, "index.js"))) {
  console.error("gen-docs: packages/sdk/dist is missing. Run `pnpm --filter @pepu-chain/sdk build` first.");
  process.exit(2);
}
const sdk = await import(pathToFileURL(join(sdkDist, "index.js")).href);
const paymaster = await import(pathToFileURL(join(sdkDist, "paymaster.js")).href);
const { PEPU_ERROR_CATALOG, PEPU_HOSTED, PEPU_ENV, PEPU_PUBLIC_ENV, PEPU_ERRORS_DOCS_URL, errorDocsUrl, getPepuAddresses, pepuMainnet } = sdk;
const { PAYMASTER_DENIAL_REASONS, PAYMASTER_REASON_CODES } = paymaster;

const LOCAL_BUNDLER = "http://localhost:4337";
const LOCAL_PAYMASTER = "http://localhost:8788";
const V1_ONLY_FROM = PAYMASTER_DENIAL_REASONS.indexOf("destination_not_globally_allowed");
const RETRYABLE_REASONS = new Set(["chain_read_failed", "rate_limited"]);

const lf = (s) => s.replace(/\r\n/g, "\n");
const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ").trim();
const overrides = new Map();
const read = (rel) => (overrides.has(rel) ? overrides.get(rel) : lf(readFileSync(join(docs, rel), "utf8")));
const banner = (what) => `<!-- Generated by scripts/gen-docs.mjs from ${what}. Do not edit by hand; run \`node scripts/gen-docs.mjs\`. -->`;

if (errorDocsUrl("UNKNOWN") !== `${BASE}/reference/errors#UNKNOWN` || PEPU_ERRORS_DOCS_URL !== `${BASE}/reference/errors`) {
  console.error("gen-docs: errorDocsUrl() no longer points at /reference/errors#<CODE>; update the generator and the docs.");
  process.exit(2);
}

const hostedLive = PEPU_HOSTED.bundlerUrl !== null && PEPU_HOSTED.paymasterBaseUrl !== null;

// ---------------------------------------------------------------- errors
const groupOf = (code) => {
  if (code.startsWith("CONFIG_")) return "Configuration";
  if (code.startsWith("AUTH_") || code.startsWith("WALLET_")) return "Auth and wallet";
  if (code.startsWith("POLICY_") || code.startsWith("SESSION_")) return "Session keys and policies";
  if (code.startsWith("PRIVY_")) return "Privy";
  if (code.startsWith("BUNDLER_")) return "Bundler";
  if (code.startsWith("PAYMASTER_")) return "Paymaster and sponsorship";
  return "Transactions and chain";
};
const GROUP_ORDER = ["Configuration", "Auth and wallet", "Privy", "Session keys and policies", "Bundler", "Paymaster and sponsorship", "Transactions and chain"];
const sorted = [...PEPU_ERROR_CATALOG].sort((a, b) => {
  const g = GROUP_ORDER.indexOf(groupOf(a.code)) - GROUP_ORDER.indexOf(groupOf(b.code));
  return g !== 0 ? g : a.code.localeCompare(b.code);
});

