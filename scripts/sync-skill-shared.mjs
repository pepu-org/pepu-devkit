#!/usr/bin/env node
// Keeps the shared skill inputs in step.
//
//   skills/_shared/chain-facts.md   GENERATED from the built SDK registry and endpoints
//   skills/_shared/rules.md         hand-written ("use the SDK, never hand-roll")
//
// Both files are copied into every skill as skills/<name>/reference/{chain-facts,rules}.md so each skill is
// self-contained when installed on its own.
//
// Usage:
//   node scripts/sync-skill-shared.mjs           regenerate and copy
//   node scripts/sync-skill-shared.mjs --check   exit 1 when anything is stale (CI)
//
// Needs the SDK built: pnpm --filter @pepu-chain/sdk build
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const skillsDir = join(root, "skills");
const sharedDir = join(skillsDir, "_shared");
const check = process.argv.includes("--check");

const sdkEntry = join(root, "packages", "sdk", "dist", "index.js");
if (!existsSync(sdkEntry)) {
  console.error("The SDK is not built. Run: pnpm --filter @pepu-chain/sdk build");
  process.exit(2);
}
const sdk = await import(pathToFileURL(sdkEntry).href);

const cell = (s) => String(s ?? "").replace(/\s+/g, " ").replace(/\|/g, "\\|").trim();
const sentence = (s) => cell(s);

function generateChainFacts() {
  const chain = sdk.pepuMainnet;
  const endpoints = sdk.resolvePepuEndpoints({ env: {} });
  const rows = sdk.getPepuAddresses(chain.id);
  const explorer = chain.blockExplorers.default;
  const live = sdk.isHostedSponsorshipLive();

  const addrTable = [
    "| Registry key | Contract | Status | Address | Note |",
    "|---|---|---|---|---|",
    ...rows.map(
      (r) =>
        `| \`${r.key}\` | ${cell(r.name)} | ${r.status} | ${r.address ? `\`${r.address}\`` : "none"} | ${sentence(r.note)} |`,
    ),
  ].join("\n");

  return `<!-- GENERATED by scripts/sync-skill-shared.mjs from the built @pepu-chain/sdk (chains, endpoints, contract registry). Do not edit: change the SDK and re-run the script. -->

# PEPU chain facts

Pepe Unchained V2, **mainnet only**. The testnet (97740) is out of scope: do not target it, do not add it to a chain list.
Always prefer the live answer: call the MCP tool \`pepu_chain_info\`, or read these from the SDK
(\`pepuMainnet\`, \`getPepuAddresses()\`, \`resolvePepuEndpoints()\` from \`@pepu-chain/sdk\`).

## Network

| | |
|---|---|
| Chain ID | \`${chain.id}\` (\`0x${chain.id.toString(16)}\`) |
| Name | ${chain.name} |
| Native token | ${chain.nativeCurrency.symbol}, ${chain.nativeCurrency.decimals} decimals (also pays gas) |
| Default RPC | \`${endpoints.rpcUrl}\` (override with \`${sdk.PEPU_ENV.rpcUrl}\`) |
| Explorer | ${explorer.name}: \`${explorer.url}\` (Blockscout), API \`${explorer.apiUrl}\` |
| Stack | Arbitrum Nitro (ArbOS 51) Orbit chain hosted by Conduit, settling to Ethereum L1 through AnyTrust |
| P256 precompile (RIP-7212) | live at \`0x0000000000000000000000000000000000000100\` (cheap passkey verification) |
| viem chain object | \`pepuMainnet\` from \`@pepu-chain/sdk\`. wagmi: \`pepuWagmiConfig()\` from \`@pepu-chain/sdk/privy/wagmi\` |

## Multicall3 is NOT at the canonical address

The canonical Multicall3 address \`${sdk.CANONICAL_MULTICALL3_ADDRESS}\` has no code on PEPU and never will (its pre-signed
deploy transaction caps gas at 1M, Nitro needs about 14.3M). PEPU's Multicall3 is
\`${chain.contracts.multicall3.address}\` (mainnet only, \`pepuMainnet.contracts.multicall3\`). Batched reads must go
through \`pepuMulticall(client, calls)\` from \`@pepu-chain/sdk\`, or a viem client whose chain is \`pepuMainnet\`. Never
paste the canonical address anywhere.

## Contracts (from \`getPepuAddresses()\`)

${addrTable}

\`paymaster\` is an alias of \`paymasterV2\`: the tiered PepuSponsoredPaymasterV7, deployed on mainnet. Deposits are one-way, so deposit only what a project needs. \`paymasterV1\` is **retired**: its deposit is 0 and it cannot sponsor anything, so never deposit to it or route work to it.

## Gas, in one paragraph

Nitro charges a dual fee: an L2 execution component and an L1 data-posting component, folded into one gas price. The base
fee is high in gwei terms (about 12,500 gwei) but a plain transfer still costs a small fraction of a cent. A high gas price is not an error.
Privy's own pre-flight balance check is over-conservative at this base fee and can refuse a send the wallet can afford, so the
PEPU templates have no "Max" button. For other wallet UIs size a max send with \`maxSendableAmount()\` and show costs with
\`estimateTransactionCost()\` and \`formatPepu()\` from \`@pepu-chain/sdk\`. Gas is never "free" unless a paymaster
actually paid it (see \`pepu_sponsorship_status\`).

## Account abstraction and sponsorship endpoints

- EntryPoint v0.7 (\`entryPoint07\`) and the Kernel v3.1 stack are deployed (table above). Use \`getPepuKernelStack(97741)\`.
- Bundler and paymaster are configured by URL: \`${sdk.PEPU_ENV.bundlerUrl}\` and \`${sdk.PEPU_ENV.paymasterUrl}\` (server) or
  \`${sdk.PEPU_PUBLIC_ENV.bundlerUrl}\` / \`${sdk.PEPU_PUBLIC_ENV.paymasterUrl}\` (browser). Resolution order:
  explicit option, env, hosted default.
- Hosted PEPU endpoints: ${
    live
      ? "**live**. The bundler is `https://bundler.pepeunchained.com` (the SDK default for `PEPU_BUNDLER_URL`). The paymaster service is `https://paymaster.pepeunchained.com` (the SDK default base for `createPaymasterApi`, probes and the doctor). The ERC-7677 URL always embeds a token, `https://paymaster.pepeunchained.com/v2/paymaster/<token>`, so set `PEPU_PAYMASTER_URL` to it (or build it with `buildErc7677Url` / `hostedErc7677Url`). A project client token (`ppt_`) works only from the project's allowed origins (otherwise `project_origin_not_allowed`), server code uses the project server key (`ppk_`), and the free tier needs a verified Privy access token from PEPU's own Privy app in the ERC-7677 context (100 PEPU/day and 50 PEPU/hour per user, TapScore only for now)."
      : "**not published** (`PEPU_HOSTED` has no URLs in this SDK version), so use the placeholders `<PEPU_BUNDLER_URL>` and `<PEPU_PAYMASTER_URL>`."
  } Local development defaults used by the PEPU services are \`http://localhost:4337\` (bundler) and \`http://localhost:8788\` (paymaster).
- Never hard-code "sponsorship works" or "sponsorship does not work". Run \`pepu_sponsorship_status\` (or \`checkSponsorship()\` from
  \`@pepu-chain/sdk\`) and report what it says.
- A paymaster URL embeds a credential: treat it as a secret and keep it server-side.

## Where to look things up

| Need | Use |
|---|---|
| Any address | \`getPepuAddresses()\` or \`getContract(name, chainId)\` (SDK), \`pepu_chain_info\` (MCP) |
| Does this address have code | \`pepu_check_contract_deployed\` |
| Explorer link | \`explorerLinks({ tx, address, token, block })\` |
| A failure | \`explainError(e)\` (SDK), \`pepu_explain_error\` (MCP) |
`;
}

/** @returns {Map<string, string>} absolute path to expected content */
function expected() {
  const out = new Map();
  const facts = generateChainFacts();
  out.set(join(sharedDir, "chain-facts.md"), facts);
  const rules = readFileSync(join(sharedDir, "rules.md"), "utf8");
  const skills = readdirSync(skillsDir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && !d.name.startsWith("_") && existsSync(join(skillsDir, d.name, "SKILL.md")))
    .map((d) => d.name);
  for (const name of skills) {
    for (const [file, body] of [
      ["chain-facts.md", facts],
      ["rules.md", rules],
    ]) {
      const stripped = body.replace(/^<!-- GENERATED[^\n]*-->\n\n?/, "");
      const header = `<!-- COPY of skills/_shared/${file}, synced by scripts/sync-skill-shared.mjs. Do not edit here: edit the source and re-run the script. -->\n\n`;
      out.set(join(skillsDir, name, "reference", file), header + stripped);
    }
  }
  return out;
}

if (!existsSync(join(sharedDir, "rules.md"))) {
  console.error("skills/_shared/rules.md is missing.");
  process.exit(2);
}

const files = expected();
let stale = 0;
for (const [path, content] of files) {
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (current === content) continue;
  stale++;
  const rel = path.slice(root.length + 1).replaceAll("\\", "/");
  if (check) {
    console.error(`stale: ${rel}`);
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote ${rel}`);
  }
}
if (check) {
  if (stale) {
    console.error(`${stale} shared skill file(s) out of date. Run: node scripts/sync-skill-shared.mjs`);
    process.exit(1);
  }
  console.log(`skill shared files in sync (${files.size} files)`);
} else {
  console.log(`synced ${files.size} files, ${stale} changed`);
}
