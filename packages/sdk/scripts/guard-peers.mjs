// Post-build step: turns "Cannot find package 'react' imported from dist/chunk-XXXX.js" into an error that names
// the @pepu-chain/sdk subpath and the exact `npm i` command. Run by `pnpm build` after tsup.
//
// - CJS: a guard is inserted at the top of each peer-dependent entry (requires run in order, so it fires first).
// - ESM: static imports are all resolved before any code runs, so a guard inside the entry can never fire.
//   Each peer-dependent entry therefore gets a sibling `<entry>.guard.js` that checks the peers with
//   `import.meta.resolve` and then loads the real entry. package.json maps it under the `node` condition only
//   (bundlers and browsers keep the plain entry, so no top-level await reaches them).
import { existsSync, readFileSync, writeFileSync } from "node:fs";

import { PEER_REQUIREMENTS } from "./peer-requirements.mjs";

const dist = new URL("../dist/", import.meta.url);

// Peers whose install can hit npm's viem/ox peer conflict (@privy-io/react-auth pins an exact viem peer).
const CONFLICT_PRONE = ["@privy-io/react-auth", "@privy-io/wagmi", "wagmi", "permissionless", "@zerodev/sdk"];

function message(subpath, peers) {
  const list = peers.join(" ");
  const conflict = peers.some((p) => CONFLICT_PRONE.includes(p))
    ? ` If npm stops with ERESOLVE (a viem peer conflict), add "overrides": { "viem": "$viem" } to package.json, as the create-pepu-app templates do, then re-run the install.`
    : "";
  return (
    `@pepu-chain/sdk/${subpath.slice(2)} needs ${peers.length === 1 ? "a peer package that is" : "peer packages that are"} not installed: ` +
    `${list}. Install with: npm i ${list}  Zero-config alternative: npx create-pepu-app.${conflict}`
  );
}

function exportedNames(source, file) {
  if (/^\s*export\s*\*/m.test(source)) throw new Error(`guard-peers: ${file} uses "export *", which cannot be wrapped`);
  const names = new Set();
  for (const m of source.matchAll(/export\s*\{([^}]*)\}/g)) {
    for (const part of (m[1] ?? "").split(",")) {
      const item = part.trim();
      if (!item) continue;
      const alias = item.split(/\s+as\s+/).pop();
      if (alias) names.add(alias.trim());
    }
  }
  for (const m of source.matchAll(/^export\s+(?:async\s+)?(?:const|let|var|function\*?|class)\s+([A-Za-z_$][\w$]*)/gm)) {
    if (m[1]) names.add(m[1]);
  }
  return [...names];
}

for (const [subpath, { file, peers }] of Object.entries(PEER_REQUIREMENTS)) {
  const msg = JSON.stringify(message(subpath, peers));
  const peersJson = JSON.stringify(peers);

  // CJS
  const cjsUrl = new URL(`${file}.cjs`, dist);
  const cjs = existsSync(cjsUrl) ? readFileSync(cjsUrl, "utf8") : undefined; // ESM-only entries have no CJS build
  if (cjs !== undefined && !cjs.includes("@pepu-chain/peer-guard")) {
    const guard =
      `/* @pepu-chain/peer-guard */(function(){var p=${peersJson};for(var i=0;i<p.length;i++){try{require.resolve(p[i])}catch(e){` +
      `if(e&&e.code==="MODULE_NOT_FOUND"){var m=${msg};var x=new Error(m);x.code="PEPU_MISSING_PEER";throw x}}}})();\n`;
    const strict = cjs.startsWith("'use strict';\n") ? "'use strict';\n" : "";
    writeFileSync(cjsUrl, strict + guard + cjs.slice(strict.length));
  }

  // ESM 
  const esmUrl = new URL(`${file}.js`, dist);
  const names = exportedNames(readFileSync(esmUrl, "utf8"), `${file}.js`);
  const base = file.split("/").pop();
  const named = names.filter((n) => n !== "default");
  const wrapper =
    `// Generated by scripts/guard-peers.mjs. Used only under the "node" export condition.\n` +
    `const peers = ${peersJson};\n` +
    `for (const peer of peers) {\n` +
    `  try {\n    import.meta.resolve?.(peer);\n  } catch (e) {\n` +
    `    if (e && e.code === "ERR_MODULE_NOT_FOUND") {\n      const err = new Error(${msg});\n      err.code = "PEPU_MISSING_PEER";\n      throw err;\n    }\n  }\n}\n` +
    `const mod = await import("./${base}.js");\n` +
    (named.length ? `export const { ${named.join(", ")} } = mod;\n` : "") +
    (names.includes("default") ? `export default mod.default;\n` : "");
  writeFileSync(new URL(`${file}.guard.js`, dist), wrapper);
}
console.log(`guard-peers: guarded ${Object.keys(PEER_REQUIREMENTS).length} entries`);
